import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createCanvas, loadImage } = require('../.tools/node_modules/@napi-rs/canvas');
const { GIFEncoder, quantize, applyPalette } = require('../.tools/node_modules/gifenc');
const { config, timeline, draw } = require('../assets/js/showcase.js');
const images = Object.fromEntries(await Promise.all(config.presets.all.pages.map(async n => [n, await loadImage(`assets/images/third/page-${String(n).padStart(2,'0')}.png`)])));
const canvas = createCanvas(config.size, config.size), ctx = canvas.getContext('2d');
await fs.mkdir('assets/exports',{recursive:true}); await fs.mkdir('artifacts',{recursive:true});
const metadata = {};
for (const [id, preset] of Object.entries(config.presets)) {
  const scenes = timeline(id), duration = scenes[scenes.length - 1].end;
  const samples = scenes.map(scene => { draw(ctx, images, scenes, scene.start + 0.5); return ctx.getImageData(0,0,config.size,config.size).data; });
  const sample = new Uint8Array(samples.reduce((n,a)=>n+a.length,0)); samples.forEach((a,i)=>sample.set(a,i*a.length));
  const palette = quantize(sample,255), transparentIndex = palette.length, outputPalette = [...palette,[0,0,0]];
  let output, fps;
  for (fps of [config.fps,8,6,4]) {
    const gif = GIFEncoder(); let previous;
    const count = fps * duration;
    for(let f=0;f<count;f++) {
      draw(ctx,images,scenes,f/fps);
      const pixels = ctx.getImageData(0,0,config.size,config.size).data;
      const indexed = applyPalette(pixels,palette), delta = indexed.slice();
      if(previous) for(let p=0;p<delta.length;p++) if(indexed[p]===previous[p]) delta[p]=transparentIndex;
      const delay = (Math.round((f+1)*100/fps)-Math.round(f*100/fps))*10;
      gif.writeFrame(delta,config.size,config.size,{palette:f===0?outputPalette:undefined,delay,repeat:0,dispose:1,transparent:f>0,transparentIndex});
      previous=indexed;
    }
    gif.finish(); output=gif.bytes(); console.log(`${id}: ${duration}s, ${fps} fps, ${(output.length/1e6).toFixed(2)} MB`);
    if(output.length<10_000_000) break;
  }
  if(output.length>=10_000_000) throw new Error(`${id} exceeds 10 MB`);
  await fs.writeFile(preset.gifUrl,output);
  metadata[id] = {bytes:output.length,fps,duration,width:config.size,height:config.size,pages:preset.pages};
  for(const [i,scene] of scenes.entries()) {
    draw(ctx,images,scenes,scene.start+0.5);
    await fs.writeFile(`artifacts/story-${id}-${i}.png`,canvas.toBuffer('image/png'));
  }
}
await fs.writeFile('assets/js/data/showcase-exports.js',`/* Generated by scripts/generate-showcase.mjs. */\n(function(root) {\n  const exports = ${JSON.stringify(metadata,null,2)};\n  root.ScrapbookExports = exports;\n  if (typeof module !== 'undefined') module.exports = exports;\n})(typeof window === 'undefined' ? globalThis : window);\n`);
console.log('Both story GIFs and download metadata saved.');
